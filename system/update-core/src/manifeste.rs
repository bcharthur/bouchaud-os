//! Signed release manifest (BOUCHAUD_MANIFESTE_V1).
//!
//! Trust chain, each link checked before the next:
//!
//!   trusted release key (compiled into the RUNNING system)
//!     -> Ed25519 signature over the EXACT manifest bytes   SIGNATURE TRUSTED
//!     -> the manifest names the image: SHA-256 and length
//!     -> the kernel re-reads the written slot from disk     HASH VALID
//!
//! Two verdicts, never merged: a correct hash of an unsigned image is not a
//! trusted image, and a trusted manifest does not make a corrupted write
//! valid.
//!
//! Canonical form -- exactly these five lines, in this order, LF only,
//! nothing before, after or between. Anything else is refused: there is
//! one byte string per manifest, so the signature covers what is parsed.
//!
//!   bouchaud-manifeste-v1
//!   version=<1..64 chars in [A-Za-z0-9._+-]>
//!   image_sha256=<64 lowercase hex>
//!   image_octets=<decimal, no leading zero, > 0>
//!   essais=<1..9>

use crate::ed25519;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct CleDeConfiance {
    pub nom: &'static str,
    pub publique: [u8; 32],
    /// A development key (generated by a bench). Reported as such, always.
    pub developpement: bool,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Manifeste {
    pub version: [u8; 64],
    pub version_len: usize,
    pub empreinte: [u8; 32],
    pub octets: u64,
    pub essais: u8,
}

impl Manifeste {
    pub fn version(&self) -> &str {
        core::str::from_utf8(&self.version[..self.version_len]).unwrap_or("?")
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RefusManifeste {
    /// Not the canonical form.
    Format,
    /// No trusted key is configured in this system.
    AucuneCleDeConfiance,
    /// No trusted key verifies this signature over these bytes.
    SignatureNonFiable,
}

fn ligne<'a>(t: &'a [u8], pos: &mut usize, cle: &[u8]) -> Result<&'a [u8], RefusManifeste> {
    let reste = &t[*pos..];
    let fin = reste.iter().position(|&b| b == b'\n').ok_or(RefusManifeste::Format)?;
    let l = &reste[..fin];
    *pos += fin + 1;
    if l.len() < cle.len() || &l[..cle.len()] != cle { return Err(RefusManifeste::Format); }
    Ok(&l[cle.len()..])
}

fn hexval(c: u8) -> Option<u8> {
    match c { b'0'..=b'9' => Some(c - b'0'), b'a'..=b'f' => Some(c - b'a' + 10), _ => None }
}

/// Parses the canonical form; refuses anything else.
pub fn analyse(t: &[u8]) -> Result<Manifeste, RefusManifeste> {
    let mut pos = 0;
    if ligne(t, &mut pos, b"bouchaud-manifeste-v1")?.len() != 0 { return Err(RefusManifeste::Format); }
    let v = ligne(t, &mut pos, b"version=")?;
    if v.is_empty() || v.len() > 64
        || !v.iter().all(|&c| c.is_ascii_alphanumeric() || matches!(c, b'.' | b'_' | b'+' | b'-')) {
        return Err(RefusManifeste::Format);
    }
    let h = ligne(t, &mut pos, b"image_sha256=")?;
    if h.len() != 64 { return Err(RefusManifeste::Format); }
    let mut empreinte = [0u8; 32];
    for i in 0..32 {
        let (a, b) = (hexval(h[2 * i]).ok_or(RefusManifeste::Format)?, hexval(h[2 * i + 1]).ok_or(RefusManifeste::Format)?);
        empreinte[i] = a << 4 | b;
    }
    let o = ligne(t, &mut pos, b"image_octets=")?;
    if o.is_empty() || o.len() > 19 || o[0] == b'0' || !o.iter().all(|c| c.is_ascii_digit()) {
        return Err(RefusManifeste::Format);
    }
    let octets = o.iter().fold(0u64, |n, &c| n * 10 + (c - b'0') as u64);
    let e = ligne(t, &mut pos, b"essais=")?;
    if e.len() != 1 || !(b'1'..=b'9').contains(&e[0]) { return Err(RefusManifeste::Format); }
    if pos != t.len() { return Err(RefusManifeste::Format); }
    let mut version = [0u8; 64];
    version[..v.len()].copy_from_slice(v);
    Ok(Manifeste { version, version_len: v.len(), empreinte, octets, essais: e[0] - b'0' })
}

/// SIGNATURE TRUSTED: the first trusted key that verifies the signature over
/// these exact bytes, then the canonical parse.
pub fn verifie_signe<'k>(
    t: &[u8],
    signature: &[u8; 64],
    cles: &'k [CleDeConfiance],
) -> Result<(Manifeste, &'k CleDeConfiance), RefusManifeste> {
    if cles.is_empty() { return Err(RefusManifeste::AucuneCleDeConfiance); }
    let cle = cles.iter().find(|c| ed25519::verifie(&c.publique, t, signature))
        .ok_or(RefusManifeste::SignatureNonFiable)?;
    Ok((analyse(t)?, cle))
}

/// Compile-time hex of a public key (for a key given at build time).
pub const fn cle_hex(h: &str) -> Option<[u8; 32]> {
    let b = h.as_bytes();
    if b.len() != 64 { return None; }
    let mut o = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        let (x, y) = (b[2 * i], b[2 * i + 1]);
        let hx = match x { b'0'..=b'9' => x - b'0', b'a'..=b'f' => x - b'a' + 10, _ => return None };
        let hy = match y { b'0'..=b'9' => y - b'0', b'a'..=b'f' => y - b'a' + 10, _ => return None };
        o[i] = hx << 4 | hy;
        i += 1;
    }
    Some(o)
}
