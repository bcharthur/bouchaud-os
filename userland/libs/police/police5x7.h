/* Lignes du glyphe de `c` (jamais NULL). */
static inline const unsigned char *police_glyphe(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    unsigned long n = sizeof(police5x7) / sizeof(police5x7[0]);
    for (unsigned long i = 0; i < n; i++)
        if (police5x7[i].c == c) return police5x7[i].lignes;
    for (unsigned long i = 0; i < n; i++)
        if (police5x7[i].c == '?') return police5x7[i].lignes;
    return police5x7[0].lignes;
}

/* Le pixel (gx, gy) du glyphe `c` (0 <= gx < 5, 0 <= gy < 7) est-il allume ? */
static inline int police_allume(char c, unsigned gx, unsigned gy)
{
    if (gx >= POLICE_L || gy >= POLICE_H) return 0;
    return (police_glyphe(c)[gy] >> (POLICE_L - 1 - gx)) & 1;
}

/* Largeur en pixels d'un texte a l'echelle `e` (avance : 6 colonnes). */
static inline unsigned police_largeur(const char *t, unsigned e)
{
    unsigned n = 0;
    while (t[n]) n++;
    return n ? (n * (POLICE_L + 1) - 1) * e : 0;
}

